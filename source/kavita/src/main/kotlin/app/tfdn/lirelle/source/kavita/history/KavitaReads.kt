package app.tfdn.lirelle.source.kavita.history

import app.tfdn.lirelle.source.kavita.library.utcInstant
import app.tfdn.lirelle.source.kavita.reading.HistoryChapterDto
import app.tfdn.lirelle.source.kavita.reading.HistoryItemDto
import java.time.Duration
import java.time.Instant
import java.time.LocalDate
import java.time.LocalDateTime
import java.time.ZoneOffset
import java.time.format.DateTimeParseException

// The reads of Kavita's chapters, built from its reading sessions: the heart of a Kavita profile's History.

/**
 * The reads of Kavita's session [items] (one item per session, series and day, with its chapters), newest end first,
 * then by chapter, then newest read first. Each chapter's entries are taken in time order (the chapter's start, then
 * the session): an entry that completed it ends a read, which starts at the first entry after the previous end. The
 * time and the sessions of a read are those of its real entries (not generated by Kavita for a book marked read or
 * for progress kept before sessions existed); none when none was real. Entries after a chapter's last end (a reading
 * not finished) make no read. Entries without a chapter or without a day are left out.
 */
internal fun readsOf(items: List<HistoryItemDto>): List<ChapterRead> = items
    .flatMap { item -> item.chapters.mapNotNull { chapter -> entryOf(item, chapter) } }
    .groupBy { it.chapter.chapterId }
    .values
    .flatMap { entries -> readsOfChapter(entries.sortedWith(compareBy({ it.start }, { it.item.sessionId }))) }
    .sortedWith(
        compareByDescending<ChapterRead> { it.endedOn }
            .thenBy { it.chapterId }
            .thenByDescending { it.readNumber },
    )

/**
 * A chapter read to the end once: from the day of the first session after its previous read (or its first session)
 * to the day of the session that completed it. A book read again has one more read, with the next [readNumber].
 */
internal data class ChapterRead(
    val chapterId: Int,
    val seriesId: Int,
    val seriesName: String?,
    val startedOn: LocalDate,
    val endedOn: LocalDate,
    val readNumber: Int,
    /** The real sessions' time; null when none was real (a book marked read). */
    val duration: Duration?,
    /** The real sessions; null when none was. */
    val sessions: Int?,
)

/**
 * One chapter's reading in one session on one day: the session's [item], the [chapter] read in it, when it started
 * and its [day].
 */
private class Entry(val item: HistoryItemDto, val chapter: HistoryChapterDto, val start: Instant?, val day: LocalDate)

/**
 * The entry of [chapter] in [item]: started at the chapter's start (else the item's), on Kavita's local date (else the
 * UTC day of its start); none for a chapter 0, or without a day.
 */
private fun entryOf(item: HistoryItemDto, chapter: HistoryChapterDto): Entry? {
    if (chapter.chapterId <= 0) return null
    val start = utcInstant(chapter.startTimeUtc) ?: utcInstant(item.startTimeUtc)
    val day = localDay(item.localDate) ?: start?.atOffset(ZoneOffset.UTC)?.toLocalDate() ?: return null
    return Entry(item, chapter, start, day)
}

/** The reads of one chapter's [entries], in time order. */
private fun readsOfChapter(entries: List<Entry>): List<ChapterRead> {
    val reads = mutableListOf<ChapterRead>()
    var span = mutableListOf<Entry>()
    for (entry in entries) {
        span += entry
        if (entry.chapter.completed) {
            reads += readOf(span, readNumber = reads.size + 1)
            span = mutableListOf()
        }
    }
    return reads
}

/** The read of a [span] of entries, the last of which completed the chapter. */
private fun readOf(span: List<Entry>, readNumber: Int): ChapterRead {
    val end = span.last()
    val real = span.filterNot { it.item.isGeneratedSession }.takeIf { it.isNotEmpty() }
    return ChapterRead(
        chapterId = end.chapter.chapterId,
        seriesId = end.item.seriesId,
        seriesName = end.item.seriesName,
        startedOn = span.first().day,
        endedOn = end.day,
        readNumber = readNumber,
        duration = real?.let { entries ->
            Duration.ofSeconds(entries.sumOf { it.chapter.durationSeconds.coerceAtLeast(0) })
        },
        sessions = real?.map { it.item.sessionId }?.distinct()?.size,
    )
}

/** The day of Kavita's local date (`2026-11-26T00:00:00`); null when absent or unreadable. */
private fun localDay(text: String?): LocalDate? {
    val date = text?.trim()?.takeIf { it.isNotEmpty() } ?: return null
    return try {
        LocalDateTime.parse(date).toLocalDate()
    } catch (_: DateTimeParseException) {
        null
    }
}
